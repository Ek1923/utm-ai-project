// ── Discord Bot management route ──────────────────────────────────────────────
import type { FastifyInstance } from 'fastify';
import { spawn, ChildProcess } from 'child_process';
import { EventEmitter }        from 'events';
import { existsSync, readFileSync, writeFileSync } from 'fs';
import { resolve, dirname }    from 'path';
import { fileURLToPath }       from 'url';

const __dirname  = dirname(fileURLToPath(import.meta.url));
const BOT_DIR    = resolve(__dirname, '../../../discord-bot');
const ENV_FILE   = resolve(BOT_DIR, '.env');
const DIST_ENTRY = resolve(BOT_DIR, 'dist/index.js');
const BUILT      = resolve(BOT_DIR, 'node_modules/.package-lock.json');

interface BotState {
  status: 'stopped' | 'starting' | 'online' | 'error';
  pid:    number | null;
  upSince: string | null;
  errorMsg: string | null;
}

let proc:    ChildProcess | null = null;
let state:   BotState = { status: 'stopped', pid: null, upSince: null, errorMsg: null };
const logBus = new EventEmitter();
logBus.setMaxListeners(50);
const logBuffer: { t: number; line: string; stream: 'out' | 'err' }[] = [];

function pushLog(line: string, stream: 'out' | 'err' = 'out') {
  const entry = { t: Date.now(), line, stream };
  logBuffer.push(entry);
  if (logBuffer.length > 500) logBuffer.shift();
  logBus.emit('line', entry);
}

function readEnv(): Record<string, string> {
  if (!existsSync(ENV_FILE)) return {};
  const out: Record<string, string> = {};
  for (const raw of readFileSync(ENV_FILE, 'utf8').split('\n')) {
    const line = raw.trim();
    if (!line || line.startsWith('#')) continue;
    const idx = line.indexOf('=');
    if (idx < 0) continue;
    out[line.slice(0, idx).trim()] = line.slice(idx + 1).trim();
  }
  return out;
}

function writeEnv(data: Record<string, string>) {
  const lines = [
    '# NEXUS Discord Bot — auto-generated by NEXUS UI',
    '',
    ...Object.entries(data).map(([k, v]) => `${k}=${v}`),
  ];
  writeFileSync(ENV_FILE, lines.join('\n') + '\n', 'utf8');
}

function startProcess() {
  if (proc) return;
  state = { status: 'starting', pid: null, upSince: null, errorMsg: null };
  pushLog('▶ Bot wordt gestart...');

  proc = spawn('node', [DIST_ENTRY], {
    cwd: BOT_DIR,
    env: { ...process.env, FORCE_COLOR: '0' },
  });

  state.pid = proc.pid ?? null;

  proc.stdout?.on('data', (d: Buffer) => {
    for (const line of d.toString().split('\n').filter(Boolean)) {
      if (line.includes('ingelogd als') || line.includes('Actief in')) {
        state.status = 'online';
        state.upSince = new Date().toISOString();
      }
      pushLog(line, 'out');
    }
  });

  proc.stderr?.on('data', (d: Buffer) => {
    for (const line of d.toString().split('\n').filter(Boolean)) {
      pushLog(line, 'err');
    }
  });

  proc.on('close', (code) => {
    pushLog(`■ Bot gestopt (exit ${code})`, 'err');
    state = { status: code === 0 ? 'stopped' : 'error', pid: null, upSince: null, errorMsg: code !== 0 ? `Exit code ${code}` : null };
    proc = null;
  });

  proc.on('error', (err) => {
    pushLog(`✗ Spawn error: ${err.message}`, 'err');
    state = { status: 'error', pid: null, upSince: null, errorMsg: err.message };
    proc = null;
  });
}

export async function discordRoutes(fastify: FastifyInstance) {

  // GET status
  fastify.get('/api/discord/status', async () => {
    const env = readEnv();
    return {
      ...state,
      hasToken:    !!env.DISCORD_TOKEN,
      hasClientId: !!env.CLIENT_ID,
      guildId:     env.GUILD_ID ?? '',
      botDir:      BOT_DIR,
      distReady:   existsSync(DIST_ENTRY),
      installed:   existsSync(BUILT),
    };
  });

  // GET config (masked)
  fastify.get('/api/discord/config', async () => {
    const env = readEnv();
    return {
      token:    env.DISCORD_TOKEN ? env.DISCORD_TOKEN.slice(0, 8) + '…' : '',
      clientId: env.CLIENT_ID    ?? '',
      guildId:  env.GUILD_ID     ?? '',
    };
  });

  // POST config — save .env
  fastify.post<{ Body: { token: string; clientId: string; guildId?: string } }>(
    '/api/discord/config',
    async (req, reply) => {
      const { token, clientId, guildId } = req.body;
      if (!token || !clientId) return reply.status(400).send({ error: 'token en clientId zijn verplicht' });
      writeEnv({ DISCORD_TOKEN: token, CLIENT_ID: clientId, GUILD_ID: guildId ?? '' });
      return { ok: true };
    }
  );

  // POST start
  fastify.post('/api/discord/start', async (_req, reply) => {
    const env = readEnv();
    if (!env.DISCORD_TOKEN || !env.CLIENT_ID) {
      return reply.status(400).send({ error: 'Sla eerst een token en client ID op.' });
    }
    if (!existsSync(DIST_ENTRY)) {
      return reply.status(400).send({ error: 'Bot is nog niet gebuild. Run npm run build in discord-bot/.' });
    }
    if (proc) return reply.status(400).send({ error: 'Bot draait al.' });
    startProcess();
    return { ok: true, status: 'starting' };
  });

  // POST stop
  fastify.post('/api/discord/stop', async (_req, reply) => {
    if (!proc) return reply.status(400).send({ error: 'Bot draait niet.' });
    proc.kill('SIGTERM');
    state.status = 'stopped';
    return { ok: true };
  });

  // POST build — runs npm run build in discord-bot/
  fastify.post('/api/discord/build', async (_req, reply) => {
    reply.raw.writeHead(200, { 'Content-Type': 'text/event-stream', 'Cache-Control': 'no-cache', Connection: 'keep-alive' });
    const send = (line: string) => reply.raw.write(`data: ${JSON.stringify({ line })}\n\n`);

    send('▶ npm run build starten...');
    const b = spawn('npm', ['run', 'build'], { cwd: BOT_DIR, shell: true });
    b.stdout?.on('data', (d: Buffer) => d.toString().split('\n').filter(Boolean).forEach(send));
    b.stderr?.on('data', (d: Buffer) => d.toString().split('\n').filter(Boolean).forEach(send));
    b.on('close', (code) => {
      send(code === 0 ? '✅ Build klaar!' : `✗ Build mislukt (exit ${code})`);
      reply.raw.end();
    });
    await new Promise(r => b.on('close', r));
  });

  // POST deploy commands
  fastify.post('/api/discord/deploy', async (_req, reply) => {
    reply.raw.writeHead(200, { 'Content-Type': 'text/event-stream', 'Cache-Control': 'no-cache', Connection: 'keep-alive' });
    const send = (line: string) => reply.raw.write(`data: ${JSON.stringify({ line })}\n\n`);

    const deployEntry = resolve(BOT_DIR, 'dist/deploy.js');
    if (!existsSync(deployEntry)) {
      send('✗ Build de bot eerst via "Build"!'); reply.raw.end(); return;
    }
    send('▶ Slash commando\'s registreren...');
    const env = readEnv();
    const d = spawn('node', [deployEntry], {
      cwd: BOT_DIR,
      env: { ...process.env, ...env, FORCE_COLOR: '0' },
    });
    d.stdout?.on('data', (x: Buffer) => x.toString().split('\n').filter(Boolean).forEach(send));
    d.stderr?.on('data', (x: Buffer) => x.toString().split('\n').filter(Boolean).forEach(send));
    d.on('close', (code) => {
      send(code === 0 ? '✅ Commando\'s geregistreerd!' : `✗ Registratie mislukt (exit ${code})`);
      reply.raw.end();
    });
    await new Promise(r => d.on('close', r));
  });

  // GET logs SSE stream
  fastify.get('/api/discord/logs', async (_req, reply) => {
    reply.raw.writeHead(200, { 'Content-Type': 'text/event-stream', 'Cache-Control': 'no-cache', Connection: 'keep-alive' });

    // Send buffered logs first
    for (const e of logBuffer.slice(-100)) {
      reply.raw.write(`data: ${JSON.stringify(e)}\n\n`);
    }

    const handler = (e: { t: number; line: string; stream: 'out' | 'err' }) => {
      reply.raw.write(`data: ${JSON.stringify(e)}\n\n`);
    };
    logBus.on('line', handler);

    const hb = setInterval(() => reply.raw.write(': hb\n\n'), 15_000);
    reply.raw.on('close', () => {
      logBus.off('line', handler);
      clearInterval(hb);
    });

    await new Promise(r => reply.raw.on('close', r));
  });
}
